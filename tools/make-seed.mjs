// Turns a cleaned seed CSV into apps-script/SeedData.gs (gitignored: it names clients).
// Usage: node tools/make-seed.mjs <seed_trips.csv>
// CSV line: date,odoStart,odoFinish,distance,source,purpose,check   (check is last and may hold commas)
import fs from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node tools/make-seed.mjs <seed_trips.csv>');
  process.exit(1);
}

const rows = fs.readFileSync(src, 'utf8').split(/\r?\n/).filter((l) => l.trim()).map((line) => {
  const f = [];
  let rest = line;
  for (let i = 0; i < 6; i++) {
    const k = rest.indexOf(',');
    f.push(k < 0 ? rest : rest.slice(0, k));
    rest = k < 0 ? '' : rest.slice(k + 1);
  }
  f.push(rest);
  const n = (s) => (s.trim() === '' ? '' : Number(s));
  return [f[0].trim(), n(f[1]), n(f[2]), Number(f[3]), f[4].trim(), f[5].trim(), f[6].trim()];
});

const out = `// Generated by tools/make-seed.mjs. Do not commit.\nvar SEED = ${JSON.stringify(rows, null, 1)};\n`;
fs.writeFileSync(new URL('../apps-script/SeedData.gs', import.meta.url), out);
console.log(`Wrote ${rows.length} rows to apps-script/SeedData.gs`);
